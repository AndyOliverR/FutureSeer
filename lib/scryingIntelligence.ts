  // Generate deterministic seed from user data
  private generateSeed(birthDate: string, fullName: string): number {
    const dateHash = birthDate.split('').reduce((acc, char) => acc + char.charCodeAt(0), 0)
    const nameHash = fullName.split('').reduce((acc, char) => acc + char.charCodeAt(0), 0)
    return (dateHash + nameHash) % 1000
  }

  // Seeded random number generator
  private seededRandom(seed: number): () => number {
    let value = seed
    return () => {
      value = (value * 9301 + 49297) % 233280
      return value / 233280
    }
  }

