  // Main method: Generate scrying vision
  async generateVision(
    method: 'crystal-ball' | 'mirror',
    question: string | undefined,
    birthDate: string | undefined,
    fullName: string | undefined,
    displayName?: string
  ): Promise<ScryingVision> {
    const isAutoGenerated = !question && !!birthDate && !!fullName
    
    if (!isAutoGenerated && !question) {
      throw new Error('Either question or birthDate/fullName must be provided')
    }
    
    // Generate symbols
    const symbols = isAutoGenerated && birthDate && fullName
      ? this.generateSymbolsFromProfile(birthDate, fullName, method)
      : question
      ? this.generateSymbolsFromQuestion(question, method)
      : []
    
    // Extract symbol types
    const colors = symbols.filter(s => s.type === 'color').map(s => s.value)
    const shapes = symbols.filter(s => s.type === 'shape').map(s => s.value)
    const images = symbols.filter(s => s.type === 'image').map(s => s.value)
    const movements = symbols.filter(s => s.type === 'movement').map(s => s.value)
    
    // Generate primary vision description
    const primaryVision = isAutoGenerated
      ? `As I gaze into the ${method === 'crystal-ball' ? 'crystal sphere' : 'reflective mirror'}, your personal scrying profile reveals ${colors.length > 0 ? `dominant colors of ${colors.slice(0, 2).join(' and ')}` : 'mystical visions'} and ${images.length > 0 ? `powerful images of ${images.slice(0, 2).join(' and ')}` : 'symbolic messages'} that speak to your spiritual path and inner vision.`
      : `As I gaze into the ${method === 'crystal-ball' ? 'crystal sphere' : 'reflective mirror'} regarding "${question}", the visions reveal ${colors.length > 0 ? colors.slice(0, 2).join(' and ') : 'mystical'} colors and ${images.length > 0 ? `images of ${images.slice(0, 2).join(' and ')}` : 'symbolic guidance'} that provide insight into your question.`
    
    // Generate interpretations
    const interpretations = this.generateVisionInterpretation(symbols, question, displayName, isAutoGenerated, method)
    
    // Generate guidance
    const guidanceData = this.generateGuidance(symbols, isAutoGenerated)
    
    // Generate personal insights if auto-generated
    const personalInsights = isAutoGenerated && birthDate && fullName
      ? this.generatePersonalInsights(birthDate, fullName, symbols)
      : { personalSymbols: [], lifePathInsights: [], spiritualGuidance: [] }
    
    // Calculate energy level
    const avgEnergy = symbols.length > 0
      ? Math.round(symbols.reduce((sum, s) => sum + s.energy, 0) / symbols.length * 10)
      : 70
    
    // Generate timing
    const timing = {
      currentPhase: this.lifePhases[Math.floor(Math.random() * this.lifePhases.length)],
      favorablePeriods: this.favorablePeriods.sort(() => 0.5 - Math.random()).slice(0, 3),
      challenges: this.challenges.sort(() => 0.5 - Math.random()).slice(0, 2),
      opportunities: this.opportunities.sort(() => 0.5 - Math.random()).slice(0, 2)
    }
    
    const vision: ScryingVision = {
      id: Date.now().toString(),
      timestamp: new Date(),
      method,
      question,
      isAutoGenerated,
      displayName,
      primaryVision,
      symbols,
      colors,
      shapes,
      images,
      movements,
      overallVision: interpretations.overallVision,
      detailedInterpretation: interpretations.detailedInterpretation,
      symbolicMeaning: interpretations.symbolicMeaning,
      insights: guidanceData.insights,
      guidance: guidanceData.guidance,
      recommendations: guidanceData.recommendations,
      energyLevel: avgEnergy,
      currentPhase: timing.currentPhase,
      favorablePeriods: timing.favorablePeriods,
      challenges: timing.challenges,
      opportunities: timing.opportunities,
      personalSymbols: personalInsights.personalSymbols,
      lifePathInsights: personalInsights.lifePathInsights,
      spiritualGuidance: personalInsights.spiritualGuidance,
      confidenceLevel: 92
    }
    
    return vision
  }

  // Save reading to Firestore
  async saveReading(userId: string, vision: ScryingVision): Promise<void> {
    if (!db) {
      console.warn('Firebase not initialized, cannot save scrying reading')
      return
    }
    
    try {
      const visionData = {
        ...vision,
        timestamp: vision.timestamp.toISOString(),
        userId
      }
      
      await setDoc(doc(db, 'scryingReadings', `${userId}_${vision.id}`), visionData)
      console.log('✅ Scrying reading saved successfully')
    } catch (error) {
      console.error('Error saving scrying reading:', error)
      throw error
    }
  }

  // Get user's scrying profile (auto-generated)
  async getUserScryingProfile(userId: string): Promise<ScryingVision | null> {
    if (!db) {
      return null
    }
    
    try {
      // Look for auto-generated profile
      const profileRef = doc(db, 'scryingProfiles', userId)
      const profileSnap = await getDoc(profileRef)
      
      if (profileSnap.exists()) {
        const data = profileSnap.data()
        return {
          ...data,
          timestamp: new Date(data.timestamp),
        } as ScryingVision
      }
      
      return null
    } catch (error) {
      console.error('Error fetching scrying profile:', error)
      return null
    }
  }

