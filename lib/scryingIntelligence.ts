  // Calculate elemental balance
  private calculateElementalBalance(symbols: ScryingSymbol[]): { fire: number; water: number; air: number; earth: number; primary: string; secondary: string } {
    const counts = { fire: 0, water: 0, air: 0, earth: 0 }
    
    symbols.forEach(symbol => {
      if (symbol.element) {
        counts[symbol.element]++
      }
    })
    
    const sorted = Object.entries(counts).sort(([, a], [, b]) => b - a)
    
    return {
      ...counts,
      primary: sorted[0][0],
      secondary: sorted[1][0]
    }
  }

