// Cache management































const dataCache = new Map<string, { data: UniversalDivinationData; timestamp: number }>();































// Using standardized cache TTL from cacheConstants
const CACHE_TTL = CACHE_CONSTANTS.DIVINATION_DATA; // 24 hours































































export function getCachedDivinationData(userId: string): UniversalDivinationData | null {































  const cached = dataCache.get(userId);































  if (cached && Date.now() - cached.timestamp < CACHE_TTL) {































    devLog.info('📦 Using cached divination data', undefined, 'aggregator');































    return cached.data;































  }































  return null;































}































































export function setCachedDivinationData(userId: string, data: UniversalDivinationData): void {































  dataCache.set(userId, { data, timestamp: Date.now() });































  devLog.debug('💾 Cached divination data');































}































































export function clearCachedDivinationData(userId?: string): void {































  if (userId) {































    dataCache.delete(userId);































    devLog.debug(`🗑️ Cleared cached data for user: ${userId}`);































  } else {































    dataCache.clear();































    devLog.debug('🗑️ Cleared all cached data');































  }































}































